export function getPointsEra(year) {
  const y = Number(year);
  return POINTS_ERAS.find(e => y >= e.from && y <= e.to) || POINTS_ERAS[POINTS_ERAS.length - 1];
}

export function pointsForPosition(pos, year) {
  const era = getPointsEra(year);
  if (pos < 1) return 0;
  return era.positions[pos - 1] ?? 0;
}

// Útil si luego pintas VR como “+1” en el top10 (2019-2024)
export function fastestLapBonusForPosition(pos, year) {
  const era = getPointsEra(year);
  if (!era.fastestLap?.bonus) return 0;
  if (era.fastestLap.requiresTop10 && pos > 10) return 0;
  return era.fastestLap.bonus;
}
